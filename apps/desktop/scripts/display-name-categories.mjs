import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Unicode 17 is the data shipped by the supported Node 24.19 runtime.
// Regenerate only when deliberately updating the native/shared name contract.
export function displayNameCategories() {
  if (process.versions.unicode !== '17.0') throw new Error('Generate display-name categories with Unicode 17.0, e.g. Node 24.19');
  const ranges = (pattern) => {
    const result = [];
    for (let code = 0; code <= 0x10ffff; code++) {
      if (!pattern.test(String.fromCodePoint(code))) continue;
      const last = result.at(-1);
      if (last && last[1] === code - 1) last[1] = code;
      else result.push([code, code]);
    }
    return result;
  };
  const table = (name, pattern) => {
    const entries = ranges(pattern).map(([start, end]) => `(0x${start.toString(16)},0x${end.toString(16)})`);
    const lines = [];
    for (let offset = 0; offset < entries.length; offset += 4) lines.push(`    ${entries.slice(offset, offset + 4).join(',')},`);
    return `const ${name}: &[(u32,u32)] = &[\n${lines.join('\n')}\n];\n`;
  };
  return '// Generated by node apps/desktop/scripts/display-name-categories.mjs using Unicode 17.0.\n'
    + '// Matches the shared DisplayNameSchema without adding a Rust Unicode dependency.\n'
    + table('DISALLOWED', /[\p{C}\p{Zl}\p{Zp}]/u)
    + table('NO_VISIBLE_CONTENT', /[\p{M}\p{Z}]/u)
    + `fn contains(ranges: &[(u32,u32)], c: char) -> bool {
    let code = c as u32;
    let at = ranges.partition_point(|(start,_)| *start <= code);
    at > 0 && code <= ranges[at - 1].1
}
pub fn disallowed(c: char) -> bool { contains(DISALLOWED, c) }
pub fn visible(c: char) -> bool { !disallowed(c) && !contains(NO_VISIBLE_CONTENT, c) }
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('../src-tauri/src/display_name_categories.rs', import.meta.url), displayNameCategories());
}
